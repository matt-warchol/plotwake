import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
import * as zod from 'zod';
const module={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('lib/connection.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,{exports:module.exports,require:()=>zod});
const {connectionSchema,connectionHelp}=module.exports;
const valid={url:'https://script.google.com/macros/s/AKfycb-test-deployment-123/exec',secret:'a'.repeat(64)};
assert.ok(connectionSchema.safeParse(valid).success);
assert.ok(connectionSchema.safeParse({...valid,url:' '+valid.url+' ',secret:' '+valid.secret+' '}).success);
for(const url of ['https://evil.example/exec',valid.url.replace('/exec','/dev'),'https://script.google.com/macros/s/AKfycb-test-deployment-123/exec?token=x'])assert.equal(connectionSchema.safeParse({...valid,url}).success,false);
assert.equal(connectionSchema.safeParse({...valid,secret:'Connection key: '+valid.secret}).success,false);
assert.match(connectionHelp('Invalid connection key.'),/same Apps Script project/);
assert.match(connectionHelp('AnalyticsAdmin is not defined'),/New version/);
const combined=connectionHelp('GA4: AnalyticsAdmin is not defined Search Console: Request had insufficient authentication scopes. Enable the Search Console API in the Google Cloud project linked to your script.');
assert.match(combined,/appsscript.json/);assert.match(combined,/authorize/);assert.match(combined,/New version/);assert.doesNotMatch(combined,/One of the Google APIs is not enabled/);
assert.match(connectionHelp('Request had insufficient authentication scopes.'),/read-only Search Console scope/);
assert.match(connectionHelp('API has not been used in project'),/Cloud project/);
assert.match(connectionHelp('Google returned a sign-in page'),/Anyone/);
assert.match(connectionHelp('timeout'),/has not been replaced/);
const ui=fs.readFileSync('src/dashboard.tsx','utf8');assert.match(ui,/className=\{"connectionresult "/);assert.match(ui,/role=\{connectionState==="error"\?"alert":"status"\}/);
console.log('OK: deployment URL/key validation, copied whitespace, actionable provider diagnostics, inline connection status.');
